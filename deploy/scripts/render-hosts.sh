#!/usr/bin/env bash
# Renders the public hostnames of deploy/apps from the ingress-nginx LoadBalancer IP:
#   deploy/apps/patches/ingress-host.yaml  (Ingress seruen -> seruen.<ip-dashes>.sslip.io)
#   deploy/apps/patches/public-url.yaml    (ConfigMap seruen-config PUBLIC_BASE_URL)
# Usage: deploy/scripts/render-hosts.sh [LB-IP]     (default: read from the cluster)
# Commit the two files afterwards so Argo CD sees them.
set -euo pipefail
SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=lib.sh
source "$SCRIPT_DIR/lib.sh"

IP=${1:-$(lb_ip)}
[[ -n "$IP" ]] || die "no LB IP (pass it as argument or install ingress-nginx first)"
HOST="seruen.${IP//./-}.sslip.io"
OUT="$DEPLOY_DIR/apps/patches"
mkdir -p "$OUT"

cat > "$OUT/ingress-host.yaml" <<EOF
# generated by deploy/scripts/render-hosts.sh for LB IP $IP
- op: replace
  path: /spec/rules/0/host
  value: $HOST
- op: replace
  path: /spec/tls/0/hosts/0
  value: $HOST
EOF

cat > "$OUT/public-url.yaml" <<EOF
# generated by deploy/scripts/render-hosts.sh for LB IP $IP
apiVersion: v1
kind: ConfigMap
metadata:
  name: seruen-config
data:
  PUBLIC_BASE_URL: https://$HOST
EOF
info "app host: https://$HOST  (patches written to deploy/apps/patches/)"
