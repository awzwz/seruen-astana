#!/usr/bin/env bash
# Generates the per-service manifests of deploy/apps (Deployments, Services, workers, CronJobs).
# Edit the lists/resources here and re-run; the output files are committed (Argo CD reads them from git).
#   deploy/scripts/gen-apps.sh
set -euo pipefail
APPS=$(cd "$(dirname "$0")/../apps" && pwd)
IMAGE=registry.digitalocean.com/seruen/seruen:latest

SERVICES=(orchestrator session context nlu retrieval ranking routing explain guard llm-gateway
          catalog-api events-api feedback-api partner-portal)
WORKERS=(normalizer dedup quality enrich embedder indexer analytics verifier)
# name|schedule (Asia/Almaty)
CRONJOBS=("collect-osm|0 3 * * *" "collect-overture|0 3 * * *" "collect-wikidata|0 3 * * *"
          "collect-wikivoyage|0 3 * * *" "collect-visitastana|0 3 * * *" "collect-sxodim|0 */3 * * *")

env_block() { # $1 = SERVICE value, $2 = indent, $3... = extra KEY=value env vars
  local svc=$1 i=$2 kv; shift 2
  cat <<EOF
${i}env:
${i}  - name: SERVICE
${i}    value: $svc
${i}  - name: OTEL_SERVICE_NAME
${i}    value: $svc
${i}  - name: POD_NAME
${i}    valueFrom: {fieldRef: {fieldPath: metadata.name}}
EOF
  for kv in "$@"; do
    printf '%s  - name: %s\n%s    value: "%s"\n' "$i" "${kv%%=*}" "$i" "${kv#*=}"
  done
  cat <<EOF
${i}envFrom:
${i}  - configMapRef: {name: seruen-config}
${i}  - secretRef: {name: seruen-secrets}
${i}  - secretRef: {name: seruen-db}
EOF
}

mkdir -p "$APPS/services" "$APPS/workers" "$APPS/cronjobs" "$APPS/jobs"
rm -f "$APPS"/services/*.yaml "$APPS"/workers/*.yaml "$APPS"/cronjobs/*.yaml

# ---- online services: Deployment + Service ---------------------------------------------------
for s in "${SERVICES[@]}"; do
  replicas=1; health=/health
  [[ $s == orchestrator || $s == retrieval ]] && replicas=2
  [[ $s == orchestrator ]] && health=/api/health
  cat > "$APPS/services/$s.yaml" <<EOF
# Online service "$s" (generated by deploy/scripts/gen-apps.sh)
apiVersion: apps/v1
kind: Deployment
metadata:
  name: $s
  labels:
    app.kubernetes.io/name: $s
    app.kubernetes.io/component: service
spec:
  replicas: $replicas
  revisionHistoryLimit: 3
  selector:
    matchLabels:
      app.kubernetes.io/name: $s
  template:
    metadata:
      labels:
        app.kubernetes.io/name: $s
        app.kubernetes.io/component: service
        app.kubernetes.io/part-of: seruen
    spec:
      imagePullSecrets:
        - name: seruen
      terminationGracePeriodSeconds: 20
      containers:
        - name: app
          image: $IMAGE
          imagePullPolicy: Always
          ports:
            - name: http
              containerPort: 8000
$(env_block "$s" "          ")
          startupProbe:
            httpGet: {path: $health, port: http}
            periodSeconds: 5
            failureThreshold: 30
          readinessProbe:
            httpGet: {path: $health, port: http}
            periodSeconds: 10
            timeoutSeconds: 3
          livenessProbe:
            httpGet: {path: $health, port: http}
            periodSeconds: 20
            timeoutSeconds: 3
            failureThreshold: 3
          resources:
            requests: {cpu: 100m, memory: 128Mi}
            limits: {cpu: 500m, memory: 384Mi}
---
apiVersion: v1
kind: Service
metadata:
  name: $s
  labels:
    app.kubernetes.io/name: $s
    app.kubernetes.io/component: service
spec:
  type: ClusterIP
  selector:
    app.kubernetes.io/name: $s
  ports:
    - name: http
      port: 8000
      targetPort: http
      appProtocol: http
EOF
done

# ---- workers: Deployment, no Service ---------------------------------------------------------
for w in "${WORKERS[@]}"; do
  note="Kafka consumer; consumer group = KAFKA_GROUP_ID"
  [[ $w == verifier ]] && note="Celery worker (broker CELERY_BROKER_URL = Redis db 2)"
  cat > "$APPS/workers/$w.yaml" <<EOF
# Worker "$w" (generated by deploy/scripts/gen-apps.sh). $note
apiVersion: apps/v1
kind: Deployment
metadata:
  name: $w
  labels:
    app.kubernetes.io/name: $w
    app.kubernetes.io/component: worker
spec:
  replicas: 1
  revisionHistoryLimit: 3
  selector:
    matchLabels:
      app.kubernetes.io/name: $w
  template:
    metadata:
      labels:
        app.kubernetes.io/name: $w
        app.kubernetes.io/component: worker
        app.kubernetes.io/part-of: seruen
    spec:
      imagePullSecrets:
        - name: seruen
      terminationGracePeriodSeconds: 30
      containers:
        - name: app
          image: $IMAGE
          imagePullPolicy: Always
$(env_block "$w" "          " "KAFKA_GROUP_ID=$w")
          resources:
            requests: {cpu: 100m, memory: 128Mi}
            limits: {cpu: 500m, memory: 384Mi}
EOF
done

# ---- CronJobs (collectors) -------------------------------------------------------------------
for c in "${CRONJOBS[@]}"; do
  name=${c%%|*}; sched=${c#*|}
  cat > "$APPS/cronjobs/$name.yaml" <<EOF
# Collector "$name" (generated by deploy/scripts/gen-apps.sh): "$sched" Asia/Almaty
apiVersion: batch/v1
kind: CronJob
metadata:
  name: $name
  labels:
    app.kubernetes.io/name: $name
    app.kubernetes.io/component: collector
spec:
  schedule: "$sched"
  timeZone: Asia/Almaty
  concurrencyPolicy: Forbid
  startingDeadlineSeconds: 600
  successfulJobsHistoryLimit: 1
  failedJobsHistoryLimit: 2
  jobTemplate:
    spec:
      backoffLimit: 2
      activeDeadlineSeconds: 3600
      ttlSecondsAfterFinished: 86400
      template:
        metadata:
          labels:
            app.kubernetes.io/name: $name
            app.kubernetes.io/component: collector
            app.kubernetes.io/part-of: seruen
        spec:
          restartPolicy: Never
          imagePullSecrets:
            - name: seruen
          containers:
            - name: app
              image: $IMAGE
              imagePullPolicy: Always
$(env_block "$name" "              ")
              resources:
                requests: {cpu: 100m, memory: 256Mi}
                limits: {cpu: "1", memory: 768Mi}
EOF
done

# ---- resources list for kustomization.yaml ---------------------------------------------------
{
  echo "# generated by deploy/scripts/gen-apps.sh - list of generated resources"
  for s in "${SERVICES[@]}"; do echo "- services/$s.yaml"; done
  for w in "${WORKERS[@]}"; do echo "- workers/$w.yaml"; done
  for c in "${CRONJOBS[@]}"; do echo "- cronjobs/${c%%|*}.yaml"; done
} > "$APPS/.generated-resources.txt"
echo "generated: ${#SERVICES[@]} services, ${#WORKERS[@]} workers, ${#CRONJOBS[@]} cronjobs in $APPS"
